CREATE TABLE IF NOT EXISTS saas_clinic_audit (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinic_id bigint NOT NULL,
    actor_id bigint NOT NULL,
    actor_email varchar(120) NOT NULL,
    action varchar(30) NOT NULL,
    previous_plan varchar(20) NOT NULL CHECK (previous_plan IN ('TRIAL', 'FREE', 'PRO', 'CONSULTORIO')),
    new_plan varchar(20) NOT NULL CHECK (new_plan IN ('TRIAL', 'FREE', 'PRO', 'CONSULTORIO')),
    previous_estado varchar(20) NOT NULL CHECK (previous_estado IN ('ACTIVA', 'SUSPENDIDA')),
    new_estado varchar(20) NOT NULL CHECK (new_estado IN ('ACTIVA', 'SUSPENDIDA')),
    reason varchar(500) NOT NULL,
    created_at timestamp(6) without time zone NOT NULL
);
LOCK TABLE saas_clinic_audit IN ACCESS EXCLUSIVE MODE;

-- IF NOT EXISTS must not silently accept a different entity mapping or FKs.
DO $$
BEGIN
    IF EXISTS (
        WITH expected(name, type) AS (VALUES
            ('id', 'bigint'), ('clinic_id', 'bigint'), ('actor_id', 'bigint'),
            ('actor_email', 'character varying(120)'), ('action', 'character varying(30)'),
            ('previous_plan', 'character varying(20)'), ('new_plan', 'character varying(20)'),
            ('previous_estado', 'character varying(20)'), ('new_estado', 'character varying(20)'),
            ('reason', 'character varying(500)'), ('created_at', 'timestamp(6) without time zone')
        ), actual AS (
            SELECT attname::text AS name, format_type(atttypid, atttypmod) AS type,
                   attnotnull, attidentity, attgenerated
            FROM pg_attribute WHERE attrelid = 'saas_clinic_audit'::regclass
              AND attnum > 0 AND NOT attisdropped
        )
        SELECT 1 FROM expected e FULL JOIN actual a USING (name)
        WHERE e.name IS NULL OR a.name IS NULL OR e.type <> a.type OR NOT a.attnotnull
           OR a.attgenerated <> '' OR (a.name = 'id' AND a.attidentity NOT IN ('a', 'd'))
           OR (a.name <> 'id' AND a.attidentity <> '')
    ) OR NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conrelid = 'saas_clinic_audit'::regclass
          AND contype = 'p' AND conkey = ARRAY[(SELECT attnum FROM pg_attribute
              WHERE attrelid = 'saas_clinic_audit'::regclass AND attname = 'id')]::smallint[]
    ) OR EXISTS (
        SELECT 1 FROM pg_constraint WHERE conrelid = 'saas_clinic_audit'::regclass AND contype = 'f'
    ) THEN
        RAISE EXCEPTION 'P4: unexpected saas_clinic_audit mapping or foreign keys; review explicitly';
    END IF;
END $$;

-- A pre-existing table must retain the enum checks Hibernate expects too.
DO $$
DECLARE
    expected record;
BEGIN
    FOR expected IN SELECT * FROM (VALUES
        ('previous_plan', 'TRIAL,FREE,PRO,CONSULTORIO'),
        ('new_plan', 'TRIAL,FREE,PRO,CONSULTORIO'),
        ('previous_estado', 'ACTIVA,SUSPENDIDA'),
        ('new_estado', 'ACTIVA,SUSPENDIDA')
    ) AS checks(column_name, allowed) LOOP
        IF NOT EXISTS (
            SELECT 1 FROM pg_constraint c JOIN pg_attribute a
              ON a.attrelid = c.conrelid AND c.conkey = ARRAY[a.attnum]
            WHERE c.conrelid = 'saas_clinic_audit'::regclass AND c.contype = 'c'
              AND c.convalidated AND a.attname = expected.column_name
              AND regexp_replace(pg_get_expr(c.conbin, c.conrelid),
                  '::(character varying|text)(\[\])?|[[:space:]()]', '', 'g') ~
                  ('^' || expected.column_name || '=ANYARRAY\[''[A-Z_]+''(,''[A-Z_]+'')*\]$')
              AND ARRAY(SELECT m[1] FROM regexp_matches(pg_get_expr(c.conbin, c.conrelid),
                       '''([A-Z_]+)''', 'g') m ORDER BY m[1]) =
                  ARRAY(SELECT v FROM unnest(string_to_array(expected.allowed, ',')) v ORDER BY v)
        ) THEN
            RAISE EXCEPTION 'P4: missing or unexpected audit enum check on %', expected.column_name;
        END IF;
    END LOOP;
END $$;

CREATE INDEX IF NOT EXISTS idx_saas_audit_clinic_created ON saas_clinic_audit (clinic_id, created_at, id);
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_index i JOIN pg_class c ON c.oid = i.indexrelid
        WHERE c.relname = 'idx_saas_audit_clinic_created' AND i.indrelid = 'saas_clinic_audit'::regclass
          AND i.indisvalid AND i.indisready AND NOT i.indisunique
          AND i.indnkeyatts = 3 AND i.indnatts = 3 AND i.indexprs IS NULL AND i.indpred IS NULL
          AND i.indkey::text = (SELECT string_agg(attnum::text, ' ' ORDER BY ord)
              FROM unnest(ARRAY['clinic_id', 'created_at', 'id']) WITH ORDINALITY AS x(name, ord)
              JOIN pg_attribute a ON a.attrelid = 'saas_clinic_audit'::regclass AND a.attname = x.name)
    ) THEN
        RAISE EXCEPTION 'P4: unexpected idx_saas_audit_clinic_created definition';
    END IF;
END $$;

CREATE OR REPLACE FUNCTION p4_reject_audit_mutation() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION USING ERRCODE = '55000', MESSAGE = 'P4: saas_clinic_audit is append-only';
END $$;
DROP TRIGGER IF EXISTS p4_saas_audit_append_only ON saas_clinic_audit;
CREATE TRIGGER p4_saas_audit_append_only
    BEFORE UPDATE OR DELETE OR TRUNCATE ON saas_clinic_audit
    FOR EACH STATEMENT EXECUTE FUNCTION p4_reject_audit_mutation();
ALTER TABLE saas_clinic_audit ENABLE ALWAYS TRIGGER p4_saas_audit_append_only;
COMMIT;
