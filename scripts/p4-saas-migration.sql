-- Explicit migration only; stop writers and select the reviewed schema first.
-- No users, user-role assignments, clinic data or existing role rows are changed.
\set ON_ERROR_STOP on
\if :{?p4_schema}
\else
    DO $$ BEGIN RAISE EXCEPTION 'P4: required psql variable p4_schema is missing'; END $$;
\endif
BEGIN;
SET LOCAL search_path = :"p4_schema", pg_catalog;
DO $$ BEGIN
    IF current_schema() IN ('pg_catalog', 'information_schema')
       OR current_schema() LIKE 'pg\_%' ESCAPE '\' THEN
        RAISE EXCEPTION 'P4: select an existing, reviewed application schema';
    END IF;
END $$;
SET LOCAL lock_timeout = '10s';
SET LOCAL statement_timeout = '10min';
SET LOCAL TIME ZONE 'UTC';
LOCK TABLE roles IN ACCESS EXCLUSIVE MODE;

DO $$
DECLARE
    name_column smallint;
    constraint_row record;
    expression text;
    enum_values text[];
    recognized integer := 0;
BEGIN
    SELECT attnum INTO STRICT name_column FROM pg_attribute
    WHERE attrelid = 'roles'::regclass AND attname = 'name' AND NOT attisdropped;
    FOR constraint_row IN
        SELECT conname, conbin, conkey, convalidated FROM pg_constraint
        WHERE conrelid = 'roles'::regclass AND contype = 'c'
          AND name_column = ANY(conkey)
    LOOP
        expression := regexp_replace(pg_get_expr(constraint_row.conbin, 'roles'::regclass),
            '::(character varying|text)(\[\])?|[[:space:]()]', '', 'g');
        IF constraint_row.conkey <> ARRAY[name_column] OR NOT constraint_row.convalidated
           OR expression !~ '^name=ANYARRAY\[''ROLE_[A-Z_]+''(,''ROLE_[A-Z_]+'')*\]$' THEN
            CONTINUE; -- Preserve custom, multi-column and unvalidated checks verbatim.
        END IF;
        SELECT array_agg(match[1] ORDER BY match[1]) INTO enum_values
        FROM regexp_matches(expression, '''(ROLE_[A-Z_]+)''', 'g') AS match;
        IF enum_values <> ARRAY['ROLE_ADMIN', 'ROLE_ASISTENTE', 'ROLE_DUENIO', 'ROLE_VETERINARIO']
           AND enum_values <> ARRAY['ROLE_ADMIN', 'ROLE_ASISTENTE', 'ROLE_DUENIO',
                                     'ROLE_SAAS_OPERATOR', 'ROLE_VETERINARIO'] THEN
            CONTINUE;
        END IF;
        recognized := recognized + 1;
        EXECUTE format('ALTER TABLE roles DROP CONSTRAINT %I', constraint_row.conname);
    END LOOP;
    IF recognized = 0 THEN
        RAISE EXCEPTION 'P4: no recognized roles.name enum check; review schema explicitly';
    END IF;
    ALTER TABLE roles ADD CONSTRAINT p4_roles_name_check CHECK
        (name IN ('ROLE_ADMIN', 'ROLE_VETERINARIO', 'ROLE_ASISTENTE', 'ROLE_DUENIO', 'ROLE_SAAS_OPERATOR'));
END $$;

INSERT INTO roles (name, description, active)
